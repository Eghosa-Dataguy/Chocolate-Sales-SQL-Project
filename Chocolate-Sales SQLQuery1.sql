----- 11. What is the total quantity sold per product category? (Join sales and products)

SELECT
    p.category,
    SUM(s.quantity) AS Total_Quantity_Sold
FROM sales s
JOIN products p
    ON s.product_id = p.product_id
GROUP BY p.category
ORDER BY Total_Quantity_Sold DESC;

----- 12. Show the store name, city, and total revenue for each store. (Join sales and stores)

SELECT
    st.store_name,
    st.city,
    SUM(s.revenue) AS Total_Revenue
FROM sales s
JOIN stores st
    ON s.store_id = st.store_id
GROUP BY st.store_name, st.city
ORDER BY Total_Revenue DESC;

----- 13. Which brand generates the highest total profit? (Join sales and products)

SELECT TOP 1
    p.brand,
    SUM(s.profit) AS Total_Profit
FROM sales s
JOIN products p
    ON s.product_id = p.product_id
GROUP BY p.brand
ORDER BY Total_Profit DESC;

----- 14. Which country generates the most total revenue? (Join sales and stores)

SELECT TOP 1
    st.country,
    SUM(s.revenue) AS Total_Revenue
FROM sales s
JOIN stores st
    ON s.store_id = st.store_id
GROUP BY st.country
ORDER BY Total_Revenue DESC;

----- 15. What is the total revenue generated by loyalty members vs non-loyalty members? (Join sales and customers)

SELECT
    CASE
        WHEN c.loyalty_member = 1 THEN 'Loyalty Member'
        ELSE 'Non-Loyalty Member'
    END AS Customer_Type,
    SUM(s.revenue) AS Total_Revenue
FROM sales s
JOIN customers c
    ON s.customer_id = c.customer_id
GROUP BY c.loyalty_member;

----- 16. List the top 5 products by total quantity sold, including the product name and brand.

SELECT TOP 5
    p.product_name,
    p.brand,
    SUM(s.quantity) AS Total_Quantity_Sold
FROM sales s
JOIN products p
    ON s.product_id = p.product_id
GROUP BY p.product_name, p.brand
ORDER BY Total_Quantity_Sold DESC;

----- 17. Which store type (retail, online, etc.) generates the most revenue?

