----- 18. What is the average order revenue for male vs female customers? (Join sales and customers)

SELECT
    c.gender,
    AVG(s.revenue) AS Average_Order_Revenue
FROM sales s
JOIN customers c
    ON s.customer_id = c.customer_id
GROUP BY c.gender;

----- 19. Which city has the highest number of orders placed? (Join sales and stores)

SELECT TOP 5
    st.city,
    COUNT(s.order_id) AS Total_Orders
FROM sales s
JOIN stores st
    ON s.store_id = st.store_id
GROUP BY st.city
ORDER BY Total_Orders DESC;

----- 20.List the products that have a unit price greater than the average unit price across all products. (Use a subquery)

SELECT DISTINCT
    p.product_name,
    s.unit_price
FROM sales s
JOIN products p
    ON s.product_id = p.product_id
WHERE s.unit_price >
(
    SELECT AVG(unit_price)
    FROM sales
)
ORDER BY s.unit_price DESC;